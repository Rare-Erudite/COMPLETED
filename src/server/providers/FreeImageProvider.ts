/**
 * FreeImageProvider — genuinely free AI image generation, no API key, no billing.
 *
 * Provider: Pollinations.ai (https://pollinations.ai)
 *   - Model: FLUX / "sana" family served behind the public endpoint
 *   - Auth: none. No account, no key, no payment method, no trial.
 *   - Cost: zero. Rate-limited by the provider, not metered.
 *   - Licence: outputs are generated per-request; the service is free for
 *     non-commercial and reasonable commercial use. See provider terms.
 *
 * This adapter exists because the Gemini image endpoint returns HTTP 429 with a
 * free-tier limit of 0 — i.e. image generation is not available on that key at
 * all. Rather than silently substituting procedural artwork and calling it AI,
 * we route to a provider that actually generates images for free.
 *
 * IMPORTANT: this module never falls back to procedural rendering itself. It
 * either returns real generated bytes or throws a typed error. The caller
 * decides what to do, and must label any procedural output as procedural.
 */

export type FreeImageErrorKind =
  | 'rate_limited'
  | 'timeout'
  | 'provider_error'
  | 'invalid_response'
  | 'unsupported';

export class FreeImageError extends Error {
  kind: FreeImageErrorKind;
  status?: number;
  constructor(kind: FreeImageErrorKind, message: string, status?: number) {
    super(message);
    this.name = 'FreeImageError';
    this.kind = kind;
    this.status = status;
  }
}

export interface FreeImageRequest {
  prompt: string;
  width?: number;
  height?: number;
  /** Optional seed for reproducibility. */
  seed?: number;
  /** Optional source image URL for image-to-image editing. */
  imageUrl?: string;
  /** Model hint; the public endpoint accepts a `model` query param. */
  model?: string;
  timeoutMs?: number;
}

export interface FreeImageResult {
  /** data: URL containing the generated image. */
  dataUrl: string;
  mimeType: string;
  bytes: number;
  width: number;
  height: number;
  provider: 'pollinations';
  model: string;
  latencyMs: number;
}

const ENDPOINT = 'https://image.pollinations.ai/prompt';

/** Map RARE's aspect-ratio vocabulary onto concrete pixel dimensions. */
export function dimensionsForAspect(aspectRatio: string, size: '1K' | '2K' | '4K'): { width: number; height: number } {
  const base = size === '4K' ? 2048 : size === '2K' ? 1536 : 1024;
  switch (aspectRatio) {
    case '16:9': return { width: base, height: Math.round((base * 9) / 16) };
    case '9:16': return { width: Math.round((base * 9) / 16), height: base };
    case '4:3': return { width: base, height: Math.round((base * 3) / 4) };
    case '3:4': return { width: Math.round((base * 3) / 4), height: base };
    case '4:1': return { width: base, height: Math.round(base / 4) };
    case '1:4': return { width: Math.round(base / 4), height: base };
    case '1:1':
    default: return { width: base, height: base };
  }
}

function sniffMime(buf: Buffer): string | null {
  if (buf.length < 12) return null;
  // JPEG
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'image/jpeg';
  // PNG
  if (buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47) return 'image/png';
  // WEBP
  if (buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP') return 'image/webp';
  return null;
}

/**
 * Generate an image. Throws FreeImageError on any failure — never returns a
 * placeholder, so a caller can never mistake a failure for a real image.
 */
export async function generateFreeImage(req: FreeImageRequest): Promise<FreeImageResult> {
  const prompt = (req.prompt || '').trim();
  if (!prompt) throw new FreeImageError('invalid_response', 'Prompt is required.');

  const width = Math.max(64, Math.min(2048, req.width ?? 1024));
  const height = Math.max(64, Math.min(2048, req.height ?? 1024));
  const timeoutMs = req.timeoutMs ?? 120_000;

  const params = new URLSearchParams({
    width: String(width),
    height: String(height),
    nologo: 'true',
    safe: 'false',
  });
  if (req.seed !== undefined) params.set('seed', String(req.seed));
  if (req.model) params.set('model', req.model);
  if (req.imageUrl) params.set('image', req.imageUrl);

  const url = `${ENDPOINT}/${encodeURIComponent(prompt)}?${params.toString()}`;

  const started = Date.now();
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);

  let response: Response;
  try {
    response = await fetch(url, {
      method: 'GET',
      signal: controller.signal,
      headers: { Accept: 'image/*' },
    });
  } catch (err: any) {
    clearTimeout(timer);
    if (err?.name === 'AbortError') {
      throw new FreeImageError('timeout', `Image provider timed out after ${timeoutMs}ms.`);
    }
    throw new FreeImageError('provider_error', `Image provider unreachable: ${err?.message || err}`);
  }
  clearTimeout(timer);

  if (response.status === 429) {
    throw new FreeImageError('rate_limited', 'Image provider rate limit reached. Try again shortly.', 429);
  }
  // Pollinations signals its free-tier throttle as HTTP 402 with a JSON body
  // ({"code":"FREE_LIMIT","message":"Free limit reached: 1 image every 45
  // seconds per IP"}). That is a rate limit, not a payment wall — the service
  // stays free, it just paces requests. Treat it as retryable.
  if (response.status === 402) {
    let detail = 'Free-tier rate limit reached (1 image / 45s per IP).';
    try {
      const body = JSON.parse(Buffer.from(await response.arrayBuffer()).toString('utf8'));
      if (body?.error?.message) detail = body.error.message;
    } catch { /* keep the default detail */ }
    throw new FreeImageError('rate_limited', detail, 402);
  }
  if (!response.ok) {
    throw new FreeImageError('provider_error', `Image provider returned HTTP ${response.status}.`, response.status);
  }

  const arrayBuf = await response.arrayBuffer();
  const buf = Buffer.from(arrayBuf);

  if (buf.length < 512) {
    throw new FreeImageError('invalid_response', `Image provider returned only ${buf.length} bytes.`);
  }

  const mimeType = sniffMime(buf);
  if (!mimeType) {
    // The provider sometimes returns an HTML error page with HTTP 200.
    const head = buf.toString('utf8', 0, 200).toLowerCase();
    if (head.includes('<html') || head.includes('<!doctype')) {
      throw new FreeImageError('invalid_response', 'Image provider returned an HTML page instead of an image.');
    }
    throw new FreeImageError('invalid_response', 'Image provider returned unrecognised bytes.');
  }

  return {
    dataUrl: `data:${mimeType};base64,${buf.toString('base64')}`,
    mimeType,
    bytes: buf.length,
    width,
    height,
    provider: 'pollinations',
    model: req.model || 'flux',
    latencyMs: Date.now() - started,
  };
}

/**
 * Generate an image, retrying the free-tier throttle with backoff.
 *
 * The provider allows one image per 45s per IP. A single request that lands
 * inside that window is not a failure — it just needs to wait. Retrying here
 * means a user asking for two images in a row gets two real images instead of
 * a silent procedural fallback on the second.
 */
export async function generateFreeImageWithRetry(
  req: FreeImageRequest,
  attempts = 3,
  baseDelayMs = 20_000
): Promise<FreeImageResult> {
  let lastError: unknown;
  for (let attempt = 0; attempt < attempts; attempt++) {
    try {
      return await generateFreeImage(req);
    } catch (err) {
      lastError = err;
      const retryable = err instanceof FreeImageError && err.kind === 'rate_limited';
      if (!retryable || attempt === attempts - 1) throw err;
      const wait = baseDelayMs * (attempt + 1);
      console.warn(`[FreeImage] rate limited, retrying in ${wait}ms (attempt ${attempt + 1}/${attempts})`);
      await new Promise((resolve) => setTimeout(resolve, wait));
    }
  }
  throw lastError;
}

/** Cheap reachability probe used by the status endpoint. */
export async function probeFreeImageProvider(timeoutMs = 20_000): Promise<{
  available: boolean;
  latencyMs: number;
  error?: string;
}> {
  const started = Date.now();
  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    const res = await fetch(
      `${ENDPOINT}/${encodeURIComponent('a small blue circle')}?width=64&height=64&nologo=true`,
      { signal: controller.signal, headers: { Accept: 'image/*' } }
    );
    clearTimeout(timer);
    const buf = Buffer.from(await res.arrayBuffer());
    const ok = res.ok && sniffMime(buf) !== null;
    return { available: ok, latencyMs: Date.now() - started, error: ok ? undefined : `HTTP ${res.status}` };
  } catch (err: any) {
    return { available: false, latencyMs: Date.now() - started, error: err?.message || String(err) };
  }
}
