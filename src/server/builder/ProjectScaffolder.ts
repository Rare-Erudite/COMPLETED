/**
 * ProjectScaffolder — create a real, buildable project on disk.
 *
 * The Universal Build flow previously only inspected RARE's own workspace; it
 * never produced a user project, so "build a project" could not actually build
 * anything. This module writes genuine project files for a set of common stacks
 * so the build/run/test stages have something real to act on.
 *
 * Every template is a minimal but complete project: a manifest, at least one
 * source file, and a test. The dependency-free templates (node-cli, node-api,
 * static-web, python-cli) build and test with no network access, so the
 * lifecycle can be exercised end to end in a constrained environment. The
 * react-vite template declares its dependencies and needs a registry install;
 * its build command says so rather than pretending to succeed offline.
 */

import fs from 'fs';
import path from 'path';

export type ProjectTemplate = 'node-cli' | 'node-api' | 'static-web' | 'python-cli' | 'react-vite';

export const PROJECT_TEMPLATES: ProjectTemplate[] = [
  'node-cli',
  'node-api',
  'static-web',
  'python-cli',
  'react-vite',
];

export interface ScaffoldResult {
  name: string;
  template: ProjectTemplate;
  /** Path relative to the workspace root, e.g. projects/my-app. */
  relativeRoot: string;
  /** Files written, relative to the workspace root. */
  files: string[];
  /** Suggested commands, or null when the stack has no such stage. */
  buildCommand: string | null;
  testCommand: string | null;
  runCommand: string | null;
  /** True when the template needs a package-registry install to build. */
  requiresInstall: boolean;
}

function slugify(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9_-]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'project'
  );
}

function pkg(name: string, objective: string, extra: Record<string, unknown> = {}): string {
  return (
    JSON.stringify(
      {
        name,
        version: '1.0.0',
        private: true,
        type: 'module',
        description: objective || `Generated by RARE Universal Build`,
        scripts: {},
        ...extra,
      },
      null,
      2,
    ) + '\n'
  );
}

