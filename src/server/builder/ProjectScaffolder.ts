const BUILD_COMMANDS: Record<ProjectTemplate, string | null> = {
  'node-cli': 'node --check src/index.js',
  'node-api': 'node --check server.js',
  'static-web': null,
  'python-cli': 'python3 -m py_compile main.py',
  'react-vite': 'npm install && npm run build',
};

const TEST_COMMANDS: Record<ProjectTemplate, string | null> = {
  'node-cli': 'npm test',
  'node-api': 'npm test',
  'static-web': null,
  'python-cli': 'python3 -m unittest',
  'react-vite': null,
};

const RUN_COMMANDS: Record<ProjectTemplate, string | null> = {
  'node-cli': 'npm start',
  'node-api': 'npm start',
  'static-web': 'open index.html',
  'python-cli': 'python3 main.py',
  'react-vite': 'npm run dev',
};

/**
 * Write a real project into `<workspaceRoot>/projects/<name>`.
 *
 * Refuses to overwrite an existing non-empty project so a user's work is never
 * clobbered by a re-run. Returns the files actually written and the commands
 * that apply to the chosen stack.
 */
export function scaffoldProject(
  workspaceRoot: string,
  name: string,
  template: ProjectTemplate,
  objective = '',
): ScaffoldResult {
  if (!PROJECT_TEMPLATES.includes(template)) {
    throw new Error(`Unknown template "${template}". Choose one of: ${PROJECT_TEMPLATES.join(', ')}.`);
  }
  const safeName = slugify(name);
  const relativeRoot = path.join('projects', safeName);
  const root = path.resolve(workspaceRoot, relativeRoot);
  const workspace = path.resolve(workspaceRoot);
  if (root !== workspace && !root.startsWith(workspace + path.sep)) {
    throw new Error('The project path escapes the workspace root.');
  }
  if (fs.existsSync(root) && fs.readdirSync(root).length > 0) {
    throw new Error(`A project named "${safeName}" already exists. Choose another name.`);
  }

  const files = TEMPLATES[template](safeName, objective);
  const written: string[] = [];
  for (const [rel, content] of Object.entries(files)) {
    const full = path.join(root, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content, 'utf-8');
    written.push(path.join(relativeRoot, rel));
  }

  return {
    name: safeName,
    template,
    relativeRoot,
    files: written,
    buildCommand: BUILD_COMMANDS[template],
    testCommand: TEST_COMMANDS[template],
    runCommand: RUN_COMMANDS[template],
    requiresInstall: template === 'react-vite',
  };
}
